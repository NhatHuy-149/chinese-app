// Step 2 (no LLM): choose the final word list.
// Rule (decided 2026-11-05): all legacy words + the TARGET most frequent everyday words.
// Output: build/selected.json (candidates with topic), plus a report of what was left out.
import { readJson, writeJson, writeText } from './lib/io.ts';
import { TOPICS } from './lib/topics.ts';
import type { Candidate } from './build-candidates.ts';
import type { Classified } from './llm-classify.ts';

const TARGET = 2500;

export type Selected = Candidate & { topic: string; everyday: boolean; rank: number };

const candidates = readJson<Candidate[]>('build/candidates.json');
const cls = new Map(readJson<Classified[]>('build/classified.json').map(c => [c.id, c]));
const withCls = candidates.map(c => ({ ...c, topic: cls.get(c.id)!.topic, everyday: cls.get(c.id)!.everyday }));

const everydayByFreq = withCls
  .filter(c => c.everyday && c.freq !== null)
  .sort((a, b) => a.freq! - b.freq!);
const top = new Set(everydayByFreq.slice(0, TARGET).map(c => c.id));
const chosen = withCls.filter(c => c.origin === 'legacy' || top.has(c.id));

// rank = our own ordering (legacy first inside a topic is applied later, at build time)
const ordered = [...chosen].sort((a, b) => (a.freq ?? Infinity) - (b.freq ?? Infinity));
const selected: Selected[] = ordered.map((c, i) => ({ ...c, rank: i + 1 }));
writeJson('build/selected.json', selected);

// --- report ------------------------------------------------------------------
const sizes = TOPICS.map(t => ({ ...t, n: selected.filter(s => s.topic === t.id).length }));
const dropped = withCls.filter(c => c.origin === 'hsk' && !c.everyday).sort((a, b) => a.freq! - b.freq!);
const lastFreq = everydayByFreq[Math.min(TARGET, everydayByFreq.length) - 1]?.freq;
const report = [
  '# Word selection report',
  '',
  `Generated by scripts/select-words.ts. Total: **${selected.length}** words ` +
    `(${selected.filter(s => s.origin === 'legacy').length} legacy, ${selected.filter(s => s.origin === 'hsk').length} new). ` +
    `Everyday cut-off: frequency rank ${lastFreq}.`,
  '',
  '## Words per topic',
  '',
  '| Topic | Words | Note |',
  '|---|---|---|',
  ...sizes.map(t => `| ${t.vi} | ${t.n} | ${t.n > 120 ? 'over 120' : t.n < 40 ? 'under 40' : ''} |`),
  '',
  `## Frequent words marked "not everyday" (first 150 of ${dropped.length})`,
  '',
  dropped.slice(0, 150).map(d => `${d.hanzi} (${d.pinyin}, ${d.en[0] ?? ''})`).join(' · '),
  '',
];
writeText('build/selection-report.md', report.join('\n'));
console.log(`selected ${selected.length}; topics over 120: ${sizes.filter(s => s.n > 120).map(s => s.id).join(', ') || 'none'}`);
